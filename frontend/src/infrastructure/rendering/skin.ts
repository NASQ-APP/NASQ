/**
 * تمييز بكسل لون البشرة.
 *
 * نطاق YCbCr الكلاسيكي، موسّع شوي عشان يغطي درجات بشرة أكثر. توسيعه أكثر
 * يبلع ألوان القماش البيج، فهذا حدّ وسط مقصود.
 *
 * يُستعمل في موضعين: ترجيح صورة القطعة وحدها، وشيل عارضة المتجر من الصورة
 * قبل تلبيسها للموديل.
 */
export function isSkin(r: number, g: number, b: number): boolean {
  const y = 0.299 * r + 0.587 * g + 0.114 * b
  if (y < 40 || y > 250) return false

  const cb = 128 - 0.168736 * r - 0.331264 * g + 0.5 * b
  const cr = 128 + 0.5 * r - 0.418688 * g - 0.081312 * b
  if (cb < 77 || cb > 132 || cr < 132 || cr > 180) return false

  // البشرة دائمًا أحمرها أعلى من أزرقها، والفرق ملموس
  return r > b + 12 && r > g + 4
}
