/**
 * حلّ اختيار الاستوديو — من المعرّفات إلى القطع.
 *
 * **من كل القطع لا من الخزانة وحدها.** كان الحلّ يبحث في «قطعي» (وهي
 * `source === 'wardrobe'` فقط)، فقطعة التجربة تدخل الاختيار ولا تُوجَد أبدًا:
 * تختفي من «إطلالتك الحالية»، ولا تُرسل مع الطلب، ولا يظهر خطأ. تضغط
 * المستخدمة «نسّقي هذي القطعة» على قطعة مستوردة فتصل الاستوديو ولا شيء فيها.
 *
 * وهو نفسه سبب «أستورد قطعة من رابط وما تنضاف»: الاستيراد ينجح، والاختيار
 * يُكتب، والاستوديو وحده لا يراها.
 *
 * والترتيب ترتيب **الاختيار** لا ترتيب المصدر: هو ترتيب التلبيس الذي يقرؤه
 * البرومبت، فقلبه يلبس القطعة في غير موضعها.
 */
export function resolveSelection<T extends { id: string }>(
  selection: readonly string[],
  items: readonly T[],
): T[] {
  const byId = new Map(items.map((item) => [item.id, item]))

  return selection
    .map((id) => byId.get(id))
    .filter((item): item is T => Boolean(item))
}
