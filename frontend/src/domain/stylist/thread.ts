/**
 * خيط المحادثة — ما جاوبت عليه المستخدمة.
 *
 * ليش دالة مستقلة بدل سطر داخل المكوّن؟ لأن الخطأ كان بالضبط هناك: الجواب
 * يُسجّل في حالة React، والطلب التالي يُبنى في **نفس الدورة** فيقرأ الحالة
 * القديمة ويرسل قائمة فاضية. فيرجع الوكيل يسأل نفس السؤال.
 *
 * القاعدة: القائمة الجديدة **قيمة تُمرَّر**، مب حالة تُقرأ لاحقًا. وهذا يخلي
 * السلوك قابلًا للاختبار بلا تشغيل الواجهة.
 */
import type { ContextualNeed } from './types'

/** يضيف حاجة مُجابة بلا تكرار، ويرجع القائمة الجديدة. */
export const withAnswered = (
  current: ContextualNeed[],
  need: ContextualNeed,
): ContextualNeed[] => (current.includes(need) ? current : [...current, need])
