/**
 * صيغة المخاطبة.
 *
 * التطبيق كُتب كلّه بصيغة المؤنث — «اختاري»، «خزانتك»، «ترتاحين لها». وهذا
 * صحيح لأغلب من يستعمله، وخاطئ لمن ليس منهم: من صرّح أنه ذكر يُخاطَب بصيغة
 * ليست صيغته في كل شاشة.
 *
 * فالنصّ يُكتب مرتين ويُختار عند العرض. والمؤنث هو الافتراضي عند جهل الجنس —
 * لا ترجيحًا لأحد، بل لأن الحسابات المنشأة قبل هذا السؤال لا جواب لها، وترك
 * ما كانت تقرؤه أهدأ من تحويلها فجأة إلى صيغة أخرى.
 */
import type { Gender } from './types'

export const forGender = (gender: Gender | undefined, feminine: string, masculine: string): string =>
  gender === 'male' ? masculine : feminine
