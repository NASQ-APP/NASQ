/**
 * رفّ قطع التجربة — خزانة ثابتة لا تُحذف ولا تُدمج.
 *
 * **ليس صفًّا في القاعدة، وهذا مقصود.** خزانة حقيقية تُعاد تسميتها وتُحذف
 * وتُخلط مع خزائن المستخدمة، وقطع التجربة ليست ملكها بعد — هي ضيوف من متاجر.
 * جعلُها صفًّا كان يعني أن حذف الخزانة يفقد القطع، وأن نقل قطعة «إلى قطع
 * التجربة» يصير خيارًا في قائمة النقل وهو بلا معنى.
 *
 * فالرفّ هنا **مشتقّ**: كل قطعة `source === 'try'` تنتمي إليه بحكم مصدرها،
 * ولا شيء يُكتب ليجعلها كذلك. لا يُحذف لأنه لا وجود له ليُحذف، ولا يُدمج لأن
 * العضوية فيه ليست حقلاً بل صفة.
 *
 * والمعرّف مُتحفَّظ: لو صادف أن لخزانة حقيقية هذا المعرّف لتضاربا، فنبقيه
 * غريبًا عن مولّد المعرّفات (`w_…`).
 */
import type { Wardrobe } from './types'

export const TRY_SHELF_ID = 'shelf:try'

export const TRY_SHELF: Wardrobe = {
  id: TRY_SHELF_ID,
  name: 'قطع التجربة',
  nameLatin: 'TRY PIECES',
  createdAt: '',
  updatedAt: '',
}

/** هل هذا المعرّف هو الرفّ الثابت لا خزانة حقيقية؟ */
export const isTryShelf = (wardrobeId: string): boolean => wardrobeId === TRY_SHELF_ID
