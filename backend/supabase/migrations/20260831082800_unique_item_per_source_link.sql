-- قطعة واحدة لكل رابط متجر، لكل مستخدمة.
--
-- الاستيراد يتكرّر بلا قصد بسهولة: ضغطتين على زر الإضافة، أو لصق رابط نسيتِ
-- إنك لصقتِه أمس. والنتيجة خزانة فيها نفس الفستان ثلاث مرات — توهم المستخدمة
-- إنها تملك ثلاثًا، وتزاحم قطعها الحقيقية.
--
-- الحارس في الواجهة يمسك الحالة الشائعة، لكنه يقرأ ذاكرة تبويب واحد. تبويبان
-- يستوردان نفس الرابط في نفس اللحظة يمرّان منه، والقاعدة وحدها تحسمها.
--
-- **جزئي**: القطع اللي تصوّرها المستخدمة بنفسها ما لها رابط، و`null` في
-- Postgres ما يساوي `null` — فبلا الشرط يصير الفهرس بلا أثر عليها أصلًا،
-- لكن ذكره يوضّح النية ويوفّر حجمه.
create unique index if not exists items_user_source_link_unique
  on items (user_id, source_link)
  where source_link is not null;
